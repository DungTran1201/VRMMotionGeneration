$ErrorActionPreference = 'Stop'
$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$gitDirRaw = git -C $repoRoot rev-parse --git-dir
if ($LASTEXITCODE -ne 0) { throw 'Current directory is not inside a Git repository.' }
$gitDir = $gitDirRaw.Trim()
if (-not [IO.Path]::IsPathRooted($gitDir)) { $gitDir = Join-Path $repoRoot $gitDir }
$hooksDir = Join-Path $gitDir 'hooks'
New-Item -ItemType Directory -Force -Path $hooksDir | Out-Null
$hookPath = Join-Path $hooksDir 'pre-commit'
if (Test-Path $hookPath) {
    $backup = "$hookPath.backup-$(Get-Date -Format 'yyyyMMdd-HHmmss')"
    Copy-Item $hookPath $backup
    Write-Host "Backed up existing hook to $backup"
}
$scriptRelative = '.agents/hooks/pre_commit.ps1'
$hook = @'
#!/usr/bin/env sh
# Generated by .agents/hooks/install-git-hooks.ps1
ROOT="$(git rev-parse --show-toplevel)"
if command -v pwsh >/dev/null 2>&1; then
  pwsh -NoProfile -ExecutionPolicy Bypass -File "$ROOT/.agents/hooks/pre_commit.ps1"
else
  powershell.exe -NoProfile -ExecutionPolicy Bypass -File "$ROOT/.agents/hooks/pre_commit.ps1"
fi
exit $?
'@
Set-Content -LiteralPath $hookPath -Value $hook -Encoding Ascii
Write-Host "Installed Git pre-commit hook at $hookPath" -ForegroundColor Green
Write-Host 'The hook checks staged diffs, common secrets, checkpoint formats and large files. It does not run the full test suite.'
